import { getDb, saveDb, logAudit, Newsletter } from './db';
import { generateNewsletterDigest } from './gemini';

let schedulerInterval: NodeJS.Timeout | null = null;

export function startBackgroundScheduler(appUrl: string) {
  if (schedulerInterval) return;

  console.log('[Scheduler] Background automation worker started');

  schedulerInterval = setInterval(async () => {
    try {
      await processScheduledTasks(appUrl);
    } catch (err) {
      console.error('[Scheduler] Error in worker tick:', err);
    }
  }, 20000); // Check every 20 seconds
}

async function processScheduledTasks(appUrl: string) {
  const db = getDb();
  const now = new Date();
  let hasChanges = false;

  // 1. Process scheduled blog articles
  for (const article of db.articles) {
    if (article.status === 'scheduled' && article.scheduledAt) {
      const scheduledTime = new Date(article.scheduledAt);
      if (scheduledTime <= now) {
        article.status = 'published';
        article.publishedAt = now.toISOString();
        article.updatedAt = now.toISOString();
        hasChanges = true;
        logAudit('article_auto_published', 'article', `Article "${article.title}" automatically published according to schedule`, 'system@healthpulse.org', article.id);
        console.log(`[Scheduler] Published article "${article.title}"`);
      }
    }
  }

  // 2. Process automated newsletter generation
  for (const auto of db.automations) {
    if (!auto.enabled) continue;
    const nextRun = new Date(auto.nextRunAt);
    if (nextRun <= now) {
      console.log(`[Scheduler] Automation triggered: "${auto.name}"`);
      
      // Find candidate articles that haven't been in recent newsletters
      const publishedArticles = db.articles
        .filter(a => a.status === 'published' && (!auto.categoryFilter || a.category === auto.categoryFilter))
        .slice(0, auto.maxArticles || 3);

      if (publishedArticles.length > 0) {
        try {
          const nextEdition = db.newsletters.length + 1;
          let generatedContent = {
            title: `${auto.name} - Issue #${nextEdition}`,
            subject: `HealthPulse Update: Issue #${nextEdition}`,
            preheader: 'Latest curated clinical insights and updates',
            introNote: 'Here is your automated briefing.',
            htmlBody: '<p>Curated briefing</p>'
          };

          try {
            generatedContent = await generateNewsletterDigest(
              publishedArticles.map(a => ({ title: a.title, excerpt: a.excerpt, slug: a.slug, category: a.category })),
              auto.introPrompt
            );
          } catch (aiErr: any) {
            console.warn('[Scheduler] AI generation warning, using fallback template:', aiErr.message);
          }

          const newNewsletter: Newsletter = {
            id: `news_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
            title: generatedContent.title,
            edition: nextEdition,
            status: auto.requireApproval ? 'draft' : 'ready',
            introNote: generatedContent.introNote,
            articleIds: publishedArticles.map(a => a.id),
            htmlBody: generatedContent.htmlBody,
            plainText: generatedContent.introNote,
            generatedBy: 'ai_automation',
            createdAt: now.toISOString()
          };

          db.newsletters.unshift(newNewsletter);

          // If autoSend is enabled and approval not required, also prepare a campaign
          if (auto.autoSend && !auto.requireApproval) {
            db.campaigns.unshift({
              id: `camp_${Date.now()}`,
              name: `Auto Broadcast: ${newNewsletter.title}`,
              subject: generatedContent.subject,
              preheader: generatedContent.preheader,
              senderName: db.meta.senderName,
              senderEmail: db.meta.senderEmail,
              replyTo: db.meta.senderEmail,
              htmlBody: generatedContent.htmlBody,
              plainText: generatedContent.introNote,
              targetSegmentId: auto.targetSegmentId,
              targetTags: [],
              status: 'scheduled',
              scheduledAt: now.toISOString(),
              totalRecipients: db.subscribers.length,
              eligibleRecipients: db.subscribers.filter(s => s.consentStatus === 'subscribed').length,
              sentCount: 0,
              failedCount: 0,
              recipientLogs: [],
              createdAt: now.toISOString(),
              updatedAt: now.toISOString()
            });
          }

          logAudit(
            'newsletter_auto_generated',
            'newsletter',
            `Automated newsletter generated by rule "${auto.name}" (Status: ${newNewsletter.status})`,
            'automation_worker',
            newNewsletter.id
          );
        } catch (genErr) {
          console.error('[Scheduler] Failed to generate newsletter for automation:', genErr);
        }
      }

      // Calculate next run date
      auto.lastRunAt = now.toISOString();
      const nextDate = new Date(now);
      if (auto.frequency === 'daily') {
        nextDate.setDate(nextDate.getDate() + 1);
      } else if (auto.frequency === 'weekly') {
        nextDate.setDate(nextDate.getDate() + 7);
      } else if (auto.frequency === 'biweekly') {
        nextDate.setDate(nextDate.getDate() + 14);
      } else if (auto.frequency === 'monthly') {
        nextDate.setMonth(nextDate.getMonth() + 1);
      }
      auto.nextRunAt = nextDate.toISOString();
      hasChanges = true;
    }
  }

  if (hasChanges) {
    saveDb(db);
  }
}
